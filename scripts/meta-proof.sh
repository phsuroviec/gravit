#!/bin/sh
# meta-proof.sh: build the judge-facing evidence page from the repo itself.
#
#   docs/meta-proof.md = what Meta models did | ledger rows | marker count | git window
#
# Nothing is asserted here that the repository cannot show. Run before recording
# the demo and again before submitting.
set -eu
cd "$(dirname "$0")/.."

OUT=docs/meta-proof.md
LEDGER=docs/meta-usage.jsonl
markers=$(grep -rhoE "meta-model: *[A-Za-z0-9.\-]+" --include='*.gd' --include='*.py' --include='*.md' \
  --include='*.tscn' --include='*.json' --include='*.ts' --exclude='meta-proof.md' \
  --exclude='attribution-policy.md' --exclude='meta-usage-log.md' . 2>/dev/null \
  | sed 's/meta-model: *//' | sort | uniq -c | sort -rn || true)
rows=0
[ -f "$LEDGER" ] && rows=$(grep -c . "$LEDGER" || true)
window=$(git log --reverse --format='%ad' --date=short 2>/dev/null | head -1 || true)
last=$(git log -1 --format='%ad' --date=short 2>/dev/null || true)
calls=$(git log --oneline 2>/dev/null | wc -l | tr -d ' ')

{
  echo "# Meta model evidence"
  echo
  echo "Generated by \`scripts/meta-proof.sh\` on $(date -u '+%Y-%m-%dT%H:%MZ'). Do not hand-edit."
  echo
  echo "## Artefacts produced by Meta models"
  echo
  echo "Every file written by \`scripts/meta_generate.py\` appends a receipt to \`$LEDGER\`."
  echo "Receipts in this repository: **$rows**."
  echo
  if [ "$rows" -gt 0 ]; then
    echo "| when | model | purpose | output | tokens |"
    echo "| --- | --- | --- | --- | --- |"
    python3 - "$LEDGER" <<'PYEOF'
import json,sys
for line in open(sys.argv[1]):
    line = line.strip()
    if not line:
        continue
    r = json.loads(line)
    u = r.get("usage") or {}
    toks = u.get("total_tokens") or "-"
    print("| " + r["ts"] + " | " + r["model"] + " | " + r.get("purpose", "") + " | `" + r["out"] + "` | " + str(toks) + " |")
PYEOF
  fi
  echo
  echo "## Markers in source"
  echo
  echo "Header/footer comments count per model (policy: \`docs/attribution-policy.md\`):"
  echo
  echo '```'
  if [ -n "$markers" ]; then echo "$markers"; else echo "(none yet)"; fi
  echo '```'
  echo
  echo "## Scope of work"
  echo
  echo "- Repo history: **$calls** commits, $window → $last (hackathon window: Oct 26 – Nov 4, 2026)."
  echo "- Only files committed in this window are part of the submission."
  echo "- Non-Meta tooling is disclosed in \`docs/meta-usage-log.md\`."
  echo
  echo "## Reproduce"
  echo
  echo '```bash'
  echo "python3 scripts/meta_generate.py --check    # key present, ledger rows"
  echo "sh scripts/check-attribution.sh             # marker audit"
  echo "sh scripts/meta-proof.sh                    # regenerate this page"
  echo '```'
} > "$OUT"

echo "wrote $OUT (ledger rows: $rows)"
